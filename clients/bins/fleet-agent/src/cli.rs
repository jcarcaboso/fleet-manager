//! The command line: every subcommand, flag and help text. `main` parses it
//! and dispatches; the help text is part of the interface, so each command
//! says whether it is read-only.

use std::path::PathBuf;

use clap::{Args, Parser, Subcommand};

use crate::service;

#[derive(Parser)]
#[command(version, about = "Fleet Manager Node Agent")]
pub struct Cli {
    /// Private durable state directory. Defaults to ~/.local/state/fleet-agent.
    #[arg(long, global = true)]
    pub state_dir: Option<PathBuf>,
    #[command(subcommand)]
    pub command: Command,
}

#[derive(Subcommand)]
pub enum Command {
    /// Create this Node's identity using a one-time enrollment token. Not
    /// read-only: it takes the state lock, so it cannot run while the service runs.
    Enroll(EnrollArgs),
    /// Poll and reconcile continuously, or once for a deployment check. Not
    /// read-only: it takes the state lock, so it cannot run while the service runs.
    Run {
        /// Reconcile all currently available Assignments, then exit.
        #[arg(long)]
        once: bool,
    },
    /// Print local identity, service state and pending report metadata without
    /// credentials. Read-only and safe to run while the service runs.
    Status,
    /// List each Target with its active Assignment and pending work, from local
    /// state. Read-only and safe to run while the service runs.
    Targets,
    /// Check local state, identity, certificate expiry and the service, and fix
    /// nothing. Exits 1 if any check fails. Read-only and safe to run while the
    /// service runs.
    Check,
    /// Measure disk usage once, waiting at most 2 seconds. Read-only (local, no
    /// Server request) and safe to run while the service runs.
    Disk,
    /// Change this Node's alias using its own client certificate. Not read-only:
    /// it takes the state lock, so it cannot run while the service runs.
    Alias { new_alias: String },
    /// Manage the background service for the current user. Not read-only: it
    /// changes the service, but takes no state lock and works while it runs.
    Service {
        #[command(subcommand)]
        action: service::ServiceCommand,
    },
    /// Show or roll back the Agent version the service runs.
    Update {
        #[command(subcommand)]
        action: UpdateCommand,
    },
}

// The flags of `enroll`; its help text is the doc comment on `Command::Enroll`.
#[derive(Args)]
pub struct EnrollArgs {
    /// Prompt for an enrollment link generated by Fleet Manager.
    #[arg(long, conflicts_with_all = ["server_url", "ca_cert", "alias", "token_file"])]
    pub link: bool,
    #[arg(long, required_unless_present = "link")]
    pub server_url: Option<String>,
    /// Public PEM CA certificate for the Fleet Server.
    #[arg(long, required_unless_present = "link")]
    pub ca_cert: Option<PathBuf>,
    #[arg(long, required_unless_present = "link")]
    pub alias: Option<String>,
    /// Token text or enrollment-create JSON. Otherwise reads FLEET_ENROLLMENT_TOKEN.
    #[arg(long)]
    pub token_file: Option<PathBuf>,
    /// Home directory under which Skills may be installed.
    #[arg(long)]
    pub home: Option<PathBuf>,
}

#[derive(Clone, Copy, Subcommand)]
pub enum UpdateCommand {
    /// Show this executable's version, the installed versions and the last
    /// update. Read-only and safe to run while the service runs.
    Status,
    /// Switch the service to the other installed version and restart it. Not
    /// read-only, but takes no state lock and works while the service runs.
    Rollback,
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_command_says_whether_it_is_read_only() {
        use clap::CommandFactory;
        let cli = Cli::command();
        let read_only = ["status", "targets", "check", "disk"];
        let mutating = ["enroll", "run", "alias", "service"];
        for name in read_only.into_iter().chain(mutating) {
            assert!(Cli::try_parse_from(["fleet-agent", name, "--help"]).is_err());
            let about = cli
                .find_subcommand(name)
                .unwrap()
                .get_about()
                .unwrap()
                .to_string();
            if read_only.contains(&name) {
                assert!(
                    about.contains("Read-only and safe to run while the service runs")
                        || about.contains("Read-only (local, no Server request) and safe")
                );
            } else {
                assert!(about.contains("Not read-only"), "{name}");
            }
        }
        let service = cli.find_subcommand("service").unwrap();
        for action in service.get_subcommands() {
            let about = action.get_about().unwrap().to_string();
            assert!(about.contains("read-only") || about.contains("Read-only"));
        }
        for args in [["targets"], ["check"], ["disk"], ["status"]] {
            assert!(Cli::try_parse_from(["fleet-agent", args[0]]).is_ok());
        }
    }

    #[test]
    fn commands_require_explicit_enrollment_settings_and_do_not_accept_raw_tokens() {
        assert!(Cli::try_parse_from(["fleet-agent", "run", "--once"]).is_ok());
        assert!(Cli::try_parse_from(["fleet-agent", "enroll"]).is_err());
        assert!(
            Cli::try_parse_from([
                "fleet-agent",
                "enroll",
                "--server-url",
                "https://fleet",
                "--ca-cert",
                "ca.pem",
                "--alias",
                "node",
                "--token",
                "secret"
            ])
            .is_err()
        );
        assert!(
            Cli::try_parse_from([
                "fleet-agent",
                "--state-dir",
                "/tmp/agent",
                "alias",
                "renamed"
            ])
            .is_ok()
        );
        assert!(Cli::try_parse_from(["fleet-agent", "enroll", "--link"]).is_ok());
        assert!(
            Cli::try_parse_from([
                "fleet-agent",
                "enroll",
                "--link",
                "--server-url",
                "https://fleet.example"
            ])
            .is_err()
        );
    }
}
